#!/usr/bin/env python3
"""Promote the 777-generated pulse notes to the actual static-site /pulse/ route.

The static Render site publishes the repository root, so public/pulse/ and
webapp/pulse/ are source artifacts but are not the canonical /pulse/ directory.
This bridge copies the newest source-bound HTML notes and links them from the
existing truth-boundary index without replacing its curated introduction.
"""
from __future__ import annotations

import html
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public" / "pulse"
SITE = ROOT / "pulse"
INDEX = SITE / "index.html"
START = "<!-- 777-LATEST-SIGNALS:START -->"
END = "<!-- 777-LATEST-SIGNALS:END -->"
MAX_LINKS = 12

def title_and_description(path: Path) -> tuple[str, str]:
    raw = path.read_text(encoding="utf-8")
    title_match = re.search(r"<title[^>]*>(.*?)</title>", raw, re.I | re.S)
    desc_match = re.search(
        r'<meta\s+name=["\']description["\']\s+content=["\'](.*?)["\']',
        raw, re.I | re.S
    )
    title = html.unescape(re.sub(r"\s+", " ", title_match.group(1)).strip()) if title_match else path.stem
    description = html.unescape(re.sub(r"\s+", " ", desc_match.group(1)).strip()) if desc_match else "Source-bound research lead; demand and revenue remain unverified."
    return title, description

def main() -> int:
    if not SOURCE.is_dir() or not INDEX.is_file():
        raise SystemExit("SITE_PUBLICATION=FAIL: expected public/pulse and pulse/index.html")
    def recency_key(path: Path) -> tuple[int, str, str]:
        # Date-prefixed expedition pages must outrank alphabetically later legacy filenames.
        # Otherwise a fresh 2026-10-13 artifact can be silently excluded from the 12-page cap.
        date_match = re.match(r"^(\\d{4}-\\d{2}-\\d{2})", path.name)
        if date_match:
            return (1, date_match.group(1), path.name)
        return (0, path.name, path.name)

    candidates = sorted(
        (p for p in SOURCE.glob("*.html") if p.name != "index.html"),
        key=recency_key,
        reverse=True,
    )[:MAX_LINKS]
    if not candidates:
        print("SITE_PUBLICATION=NO_SOURCE_BOUND_PAGES")
        return 0

    copied = []
    entries = []
    for source in candidates:
        target = SITE / source.name
        if not target.exists() or target.read_bytes() != source.read_bytes():
            shutil.copy2(source, target)
            copied.append(target.relative_to(ROOT).as_posix())
        title, description = title_and_description(source)
        href = "/pulse/" + html.escape(source.name, quote=True)
        entries.append(
            '<li style="padding:12px 0;border-top:1px solid #2a3b51">'
            f'<a href="{href}">{html.escape(title)}</a>'
            '<p style="margin:4px 0;color:#b4c0cf">'
            f'{html.escape(description)} '
            'Status: UNVERIFIED research lead, not evidence of buyer demand or revenue.'
            '</p></li>'
        )

    section = (
        f"{START}\n<section class=\"panel\" id=\"recent-777-signals\">"
        "<h2>Recent source-bound signals</h2>"
        "<p>Fresh research leads generated by 777. Each note links to its source; "
        "claims remain unverified until independently corroborated. These notes "
        "are not endorsements, buyer intent, or revenue evidence.</p>"
        "<ul style=\"list-style:none;padding:0\">"
        + "\n".join(entries)
        + "</ul></section>\n"
        + END
    )
    index = INDEX.read_text(encoding="utf-8")
    if START in index and END in index:
        index = re.sub(re.escape(START) + r".*?" + re.escape(END), section, index, flags=re.S)
    else:
        if "</main>" not in index:
            raise SystemExit("SITE_PUBLICATION=FAIL: canonical pulse index has no </main> anchor")
        index = index.replace("</main>", section + "\n</main>", 1)
    if index != INDEX.read_text(encoding="utf-8"):
        INDEX.write_text(index, encoding="utf-8")
        copied.append(INDEX.relative_to(ROOT).as_posix())

    print("SITE_PUBLICATION=PASS")
    print(f"SOURCE_PAGES_SELECTED={len(candidates)}")
    print(f"SITE_FILES_CHANGED={len(copied)}")
    for path in copied:
        print(f"SITE_FILE={path}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
