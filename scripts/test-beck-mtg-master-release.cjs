'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const mtg=read('public/mtg/index.html'),success=read('public/success.html'),thanks=read('public/thanks.html');
const ret=read('public/assets/checkout-return.js'),template=JSON.parse(read('config/mtg-master-community.json'));
const market=read('public/marketplace.html'),paid=read('public/mtg/diagnostic.html'),manifest=JSON.parse(read('silos/mtg/silo.json'));
assert.equal((mtg.match(/data-auction-slot=/g)||[]).length,3,'three actual auction placeholders');
assert.equal((mtg.match(/class="hub-free-card"/g)||[]).length,5,'five functional free entry cards');
assert(mtg.indexOf('id="welcome"')<mtg.indexOf('id="auctions"'),'free value first');
assert(mtg.indexOf('id="cards"')<mtg.indexOf('hub-membership'),'monetization below community/catalogue');
for(const s of ['/mtg/tools/','/mtg-list/','/mtg/community/','/mtg/market/'])assert(mtg.includes('href="'+s)||mtg.includes('href="'+s+'#'),'free route '+s);
assert(!mtg.includes('NZ$29 · Digital product'),'paid SKU must not be first tool carousel card');
assert(mtg.includes('lowest Patreon tier includes one diagnostic per month'),'monthly perk contextual, not hero');
assert(paid.includes('NZ$29')&&!paid.includes('Free Commander deck check'),'paid diagnostic retained');
assert(market.includes('NZ$29 · PAID DIGITAL PRODUCT · CHECKOUT HELD'),'paid catalogue unchanged');
assert(!paid.includes('https://buy.stripe.com/'),'direct checkout cannot be re-enabled by markup');
assert(manifest.slug==='mtg'&&manifest.browse_free===true&&manifest.success_fee_peer===0,'free entry and fee contract');
for(const file of [success,thanks]){
 assert(file.includes('id="return-title"'),'status-driven return');
 assert(file.includes('/assets/checkout-return.js'),'only server verification may change return state');
 assert(!/Payment received|Payment successful|Order confirmed/i.test(file),'no false confirmation');
 assert(!file.includes('id="return-next" class="bec-btn" href="https://'),'no unlocked action in default HTML');
}
assert(ret.includes('/functions/v1/mtg-commander-status?session_id='),'checkout calls deployed Supabase server');
assert(ret.includes("case 'paid_pending_record':"),'pending webhook state distinguished');
assert(ret.includes("case 'paid_recorded':"),'DB-confirmed state distinct');
assert(ret.includes('attempts<6'),'bounded polling');
const edge=read('supabase/functions/mtg-commander-status/index.ts');
assert(edge.includes('line_items.data.price.product'),'deployed edge inspects actual bought product');
assert(edge.includes('marketplace_orders')&&edge.includes('marketplace_fulfillments'),'deployed edge reads webhook-backed ledger');
assert(!/\.(insert|upsert|update|delete)\s*\(/.test(edge),'return verifier must be read-only');
assert(edge.includes("LOOKUP='COMMANDER-DECK-DIAGNOSTIC-001'"),'canonical Stripe lookup key');
assert(edge.includes('p.unit_amount===2900'),'price in minor units');
const webhook=read('supabase/functions/stripe-revenue-41104f355d6878cdd6d1f9dc/index.ts');
assert(webhook.includes('MTG_DIAG_CONTRACT_MISMATCH'),'live webhook candidate must fail closed before settlement');
assert(webhook.includes('line_items.data.price.product'),'webhook must inspect purchased product');
assert(!webhook.includes('sku=listing.sku===\"COMMANDER-DECK-DIAGNOSTIC-001\" ? \"CMD-DIAG-29\"'),'no legacy alias remap');
assert(template.member_benefits[0].included_per_month===1,'Patreon monthly included diagnostic');
const intakeHtml=read('public/diagnostic-input.html');
const intakeHandler=read('handlers/commercial-diagnostic-input.ts');
const gateway=read('api/[...route].ts');
assert(gateway.includes('"/api/commercial/input"'),'paid diagnostic form must have an actual gateway route');
assert(gateway.includes('../handlers/commercial-diagnostic-input.ts'),'gateway must use existing paid-intake bridge');
assert(intakeHtml.includes("fetch('/api/commercial/input'"),'paid diagnostic intake form posts to real same-origin endpoint');
assert(ret.includes("next.href='/diagnostic-input.html?session_id='"),'paid recorded buyer must reach paid decklist form');
assert(intakeHandler.includes('/functions/v1/marketplace-diagnostic-input'),'bridge must reuse existing deployed Supabase diagnostic service');
assert(intakeHandler.includes('report_delivered:false'),'queued intake must never claim report delivered');
console.log('BECK_MTG_COMMUNITY_CHECKOUT_PASS: free hub first, NZD29 paid offer secondary, payment processing fail-closed');
