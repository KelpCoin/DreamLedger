'use strict';
const fs=require('fs');
const path=require('path');
const crypto=require('crypto');
const ROOT=path.join(__dirname,'..');
const INDEX=path.join(ROOT,'compiled','website','index.html');
if(!fs.existsSync(INDEX))throw new Error('public index missing: '+INDEX);
const html=fs.readFileSync(INDEX,'utf8');
const required=['Find it.','Build it.','Own it.','Inverse Shopping','ELoM','Billboard','Commander Deck Diagnostic','NZ$29'];
const forbidden=['Amplissa','HappyHomarid','CollectorsCoast','adult-only','adult only','stripe_secret_key','stripe_webhook_secret','/var/data/'];
const lower=html.toLowerCase();
const missing=required.filter(x=>!lower.includes(x.toLowerCase()));
const leaked=forbidden.filter(x=>lower.includes(x.toLowerCase()));
const proof={status:missing.length===0&&leaked.length===0?'PASS':'FAIL',mode:'DIVERSIFIED_DOORWAY',file:INDEX,sha256:crypto.createHash('sha256').update(html,'utf8').digest('hex'),required_present:required.map(x=>({token:x,present:lower.includes(x.toLowerCase())})),forbidden_absent:forbidden.map(x=>({token:x,absent:!lower.includes(x.toLowerCase())})),missing,leaked,generated_at:new Date().toISOString()};
fs.mkdirSync(path.join(ROOT,'RUN-PROOFS'),{recursive:true});
fs.writeFileSync(path.join(ROOT,'RUN-PROOFS','E1-CATALOG-POLISH-PROOF.json'),JSON.stringify(proof,null,2)+'\n');
console.log(JSON.stringify(proof,null,2));
if(proof.status!=='PASS')process.exit(1);
