'use strict';
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'../..');
const input=path.join(root,'proof/gauntlet/labeled-eval.json');
const hash=s=>crypto.createHash('sha256').update(s).digest('hex');
const doc=JSON.parse(fs.readFileSync(input,'utf8'));
const cases=Array.isArray(doc.cases)?doc.cases:[];
const valid=cases.filter(x=>['PASS','FAIL'].includes(x.expected)&&['PASS','FAIL'].includes(x.actual)&&typeof x.trace_id==='string'&&x.trace_id.trim());
const TP=valid.filter(x=>x.expected==='FAIL'&&x.actual==='FAIL').length;
const FN=valid.filter(x=>x.expected==='FAIL'&&x.actual==='PASS').length;
const TN=valid.filter(x=>x.expected==='PASS'&&x.actual==='PASS').length;
const FP=valid.filter(x=>x.expected==='PASS'&&x.actual==='FAIL').length;
const tprDen=TP+FN,tnrDen=TN+FP;
const TPR=tprDen?TP/tprDen:null,TNR=tnrDen?TN/tnrDen:null;
const reasons=[];
if(cases.length!==valid.length)reasons.push('INVALID_LABEL_ROWS');
if(valid.length<100)reasons.push('AT_LEAST_100_INDEPENDENT_LABELS_REQUIRED');
if(!tprDen||!tnrDen)reasons.push('BOTH_EXPECTED_CLASSES_REQUIRED');
const enough=valid.length>=100&&tprDen>0&&tnrDen>0&&cases.length===valid.length;
const passed=enough&&TPR>=0.9&&TNR>=0.9;
const verdict=passed?'PASS':enough?'REJECT':'HOLD';
const report={schema:'DREAMLEDGER/GAUNTLET-EVALUATION/v1',verdict,activation_ready:passed,source:'independently labelled cases; no self-scored or synthetic labels accepted as validation',sample_count:valid.length,minimum_sample_count:100,confusion_matrix:{true_positive_failure_detects:TP,false_negative_missed_failures:FN,true_negative_passes:TN,false_positive_false_rejections:FP},tpr:TPR,tnr:TNR,thresholds:{tpr_min:0.9,tnr_min:0.9},reasons,labels_sha256:hash(JSON.stringify(doc)),generated_at:new Date().toISOString(),truth_boundary:'This measures labelled evaluation cases only. It does not establish payment, fulfillment, buyer, or revenue truth.'};
console.log(JSON.stringify(report,null,2));
if(verdict==='REJECT')process.exitCode=1;
