'use strict';
const fs=require('fs');
const path=require('path');
const ROOT=path.join(__dirname,'..','..');
const checks=[];
function ok(name,pass,detail){checks.push({name,status:pass?'PASS':'FAIL',detail})}
function readIfPresent(file){try{return fs.readFileSync(file,'utf8')}catch(e){if(e&&e.code==='ENOENT')return null;throw e}}
const template=path.join(ROOT,'BEC-PRIME','surface','molt-beach.v1.template.html');
const compiler=path.join(ROOT,'BEC-PRIME','compiler','MoltBeachCompiler.js');
const checkout=path.join(ROOT,'api','molt-beach-checkout.ts');
const inventory=path.join(ROOT,'api','molt-beach-inventory.ts');
const webhook=path.join(ROOT,'api','molt-beach-webhook.ts');
const publicServer=path.join(ROOT,'public','server.js');
for(const f of [template,compiler,checkout,inventory,webhook]) ok(path.relative(ROOT,f),fs.existsSync(f),'file exists');
const templateText=readIfPresent(template);
const html=(templateText||'').toLowerCase();
for(const token of ['amplissa','adult-only','stripe_secret_key','stripe_webhook_secret','bec-prime'])ok('public silo gate '+token,templateText!==null&&!html.includes(token),templateText===null?'template unavailable':'forbidden token absent');
const canvasWidth=/\.board\{[^}]*width:\s*1000px/i.test(html);
const canvasHeight=/\.board\{[^}]*height:\s*1000px/i.test(html);
const canvasLabel=/1,?000\s*x\s*1,?000 canvas/i.test(html);
ok('canvas',canvasWidth&&canvasHeight&&canvasLabel,'1000x1000 canvas');
ok('agent inventory',(readIfPresent(inventory)||'').includes('molt_beach_campaigns'),'Supabase-backed inventory API');
ok('dynamic checkout',(readIfPresent(checkout)||'').includes('STRIPE_SECRET_KEY'),'server-side Stripe checkout');
ok('paid webhook',(readIfPresent(webhook)||'').includes('checkout.session.completed'),'paid activation webhook');
ok('public board route',(readIfPresent(publicServer)||'').includes('/billboard'),'Render public /billboard route');
const fail=checks.filter(x=>x.status==='FAIL');
const missing_files=[template,compiler,checkout,inventory,webhook].filter(f=>!fs.existsSync(f)).map(f=>path.relative(ROOT,f));
const proof={type:'molt-beach-mvp-verification',status:fail.length?'FAIL':'PASS',missing_files,pc_required:false,checks,verified_at:new Date().toISOString(),truth_rule:'Source checks do not authorize public activation or payments.'};
const out=path.join(ROOT,'PROOF-MOLT-BEACH-MVP.json');
fs.writeFileSync(out,JSON.stringify(proof,null,2)+'\n');
console.log(JSON.stringify(proof,null,2));
if(fail.length)process.exitCode=1;
