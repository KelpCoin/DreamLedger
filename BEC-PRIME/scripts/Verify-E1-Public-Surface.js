'use strict';
const fs=require('fs');
const path=require('path');
const crypto=require('crypto');
const ROOT=path.join(__dirname,'..');
const INDEX=path.join(ROOT,'compiled','website','index.html');
const PROOF_DIR=path.join(ROOT,'RUN-PROOFS');
const PROOF=path.join(PROOF_DIR,'E1-PUBLIC-SURFACE-PROOF.json');
const REQUIRED=['DreamLedger','Find it.','Build it.','Own it.','Inverse Shopping','ELoM','Billboard','Commander Deck Diagnostic','NZ$29','https://buy.stripe.com/00w7sLaXP01n96nbN2dwc2l'];
const FORBIDDEN=['Dream Ledger Deck','Agentic Commerce Readiness Audit','One offer. One price.','Buy the Diagnostic - NZ$29','CollectorsCoast','HappyHomarid','Amplissa','stripe_secret_key','stripe_webhook_secret','/var/data/'];
if(!fs.existsSync(INDEX))throw Error('public index missing');
const html=fs.readFileSync(INDEX,'utf8');
const lower=html.toLowerCase();
const missing=REQUIRED.filter(x=>!lower.includes(x.toLowerCase()));
const leaked=FORBIDDEN.filter(x=>lower.includes(x.toLowerCase()));
const routes={mtg:lower.includes('href="/mtg.html"')||lower.includes('href="/mtg"'),marketplace:lower.includes('href="/marketplace.html"'),digital_products:lower.includes('href="/digital-products.html"'),avatar:lower.includes('href="/avatar.html"'),elom:lower.includes('href="/elom.html"')};
const routeFailures=Object.keys(routes).filter(k=>!routes[k]);
const proof={schema:'dreamledger-public-diversified-surface-proof-v4',status:missing.length===0&&leaked.length===0&&routeFailures.length===0?'PASS':'FAIL',generated_at:new Date().toISOString(),source:'BEC-PRIME/compiled/website/index.html',sha256:crypto.createHash('sha256').update(html,'utf8').digest('hex'),required_present:REQUIRED.map(x=>({token:x,present:lower.includes(x.toLowerCase())})),forbidden_absent:FORBIDDEN.map(x=>({token:x,absent:!lower.includes(x.toLowerCase())})),routes,missing_required:missing,leaked_forbidden:leaked,route_failures:routeFailures};
fs.mkdirSync(PROOF_DIR,{recursive:true});
fs.writeFileSync(PROOF,JSON.stringify(proof,null,2)+'\n');
console.log(JSON.stringify({...proof,proof_path:PROOF},null,2));
if(proof.status!=='PASS')process.exit(1);
