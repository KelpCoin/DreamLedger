'use strict';
const fs=require('fs');
const path=require('path');
const crypto=require('crypto');
const ROOT=path.join(__dirname,'..');
const SITE=path.join(ROOT,'compiled','website');
const INDEX=path.join(SITE,'index.html');
const PROOF_DIR=path.join(ROOT,'RUN-PROOFS');
const PROOF=path.join(PROOF_DIR,'E1-PUBLIC-SURFACE-PROOF.json');
const REQUIRED=['DreamLedger','FIND SOMETHING','GOOD.','Shop the collection.','Billboard','MTG','DreamMeez','NZ$50'];
const FORBIDDEN=['Dream Ledger Deck','Agentic Commerce Readiness Audit','One offer. One price.','Buy the Diagnostic - NZ$29','CollectorsCoast','HappyHomarid','Amplissa','stripe_secret_key','stripe_webhook_secret','/var/data/','ELOHIM','Economic Court','Truth Oracle','Gauntlet','MCP gateway','Agentic commerce','AI agent','VISA','MASTERCARD','AMEX'];
const ROUTES={mtg:lower=>lower.includes('href="/mtg"')||lower.includes('href="/mtg.html"'),billboard:lower=>lower.includes('href="/billboard"')||lower.includes('href="/billboard.html"')};
if(!fs.existsSync(INDEX))throw Error('public index missing: '+INDEX);
const html=fs.readFileSync(INDEX,'utf8');
const lower=html.toLowerCase();
const missing=REQUIRED.filter(x=>!lower.includes(x.toLowerCase()));
const leaked=FORBIDDEN.filter(x=>lower.includes(x.toLowerCase()));
const routes={mtg:ROUTES.mtg(lower),billboard:ROUTES.billboard(lower)};
const routeFailures=Object.keys(routes).filter(k=>!routes[k]);
const proof={schema:'dreamledger-public-e1-surface-proof-v5',status:missing.length===0&&leaked.length===0&&routeFailures.length===0?'PASS':'FAIL',generated_at:new Date().toISOString(),source:'BEC-PRIME/compiled/website/index.html',sha256:crypto.createHash('sha256').update(html,'utf8').digest('hex'),required_present:REQUIRED.map(x=>({token:x,present:lower.includes(x.toLowerCase())})),forbidden_absent:FORBIDDEN.map(x=>({token:x,absent:!lower.includes(x.toLowerCase())})),routes,missing_required:missing,leaked_forbidden:leaked,route_failures:routeFailures,policy:'Validate the current catalogue-first public surface. Do not require retired marketing copy or obsolete product SKUs.'};
fs.mkdirSync(PROOF_DIR,{recursive:true});
fs.writeFileSync(PROOF,JSON.stringify(proof,null,2)+'\n','utf8');
console.log(JSON.stringify({...proof,proof_path:PROOF},null,2));
if(proof.status!=='PASS')process.exit(1);
