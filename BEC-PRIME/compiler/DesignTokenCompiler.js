'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const TOKEN_FILE = path.join(ROOT, 'BEC-PRIME', 'design', 'enterprise.tokens.json');
const OUTPUT_FILE = path.join(ROOT, 'public', 'assets', 'dl-design-tokens.css');
const MASTER_CSS = path.join(ROOT, 'public', 'assets', 'silo-master.css');
const FONT_IMPORT = '@import url("https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600&family=Inter:wght@400;500;600;700&display=swap");';

function fail(message) { throw new Error('ELOHIM_DESIGN_TOKEN_GATE: ' + message); }
function kebab(value) {
  return String(value).replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/_/g, '-').toLowerCase();
}
function cssValue(type, value, tokenPath) {
  if (type === 'color') {
    if (typeof value === 'string' && /^#[0-9a-f]{6}$/i.test(value)) return value.toUpperCase();
    if (value && typeof value === 'object' && /^#[0-9a-f]{6}$/i.test(value.hex || '')) return value.hex.toUpperCase();
    fail(tokenPath + ' must contain a six-digit sRGB hex color');
  }
  if (type === 'dimension') {
    if (!value || typeof value !== 'object' || !Number.isFinite(value.value) || !['px', 'rem'].includes(value.unit)) fail(tokenPath + ' must be a DTCG dimension object');
    if (tokenPath.startsWith('spacing.') && value.unit === 'px' && value.value % 4 !== 0) fail(tokenPath + ' must use the 4px spacing grid');
    return String(value.value) + value.unit;
  }
  if (type === 'fontFamily') {
    const list = Array.isArray(value) ? value : [value];
    if (!list.length || list.some(v => typeof v !== 'string' || !v.trim())) fail(tokenPath + ' must contain font family names');
    return list.map(v => /^(system-ui|sans-serif|serif|monospace|ui-monospace)$/.test(v) ? v : '"' + v.replace(/"/g, '') + '"').join(', ');
  }
  if (type === 'fontWeight') {
    if (!(typeof value === 'number' && value >= 1 && value <= 1000) && !['thin','extra-light','light','regular','medium','semi-bold','bold','extra-bold','black'].includes(value)) fail(tokenPath + ' has invalid font weight');
    return String(value);
  }
  if (type === 'number') {
    if (!Number.isFinite(value)) fail(tokenPath + ' must be numeric');
    return String(value);
  }
  fail(tokenPath + ' uses unsupported DTCG type ' + type);
}
function collect(node, prefix = [], inheritedType = null, out = []) {
  if (!node || typeof node !== 'object' || Array.isArray(node)) return out;
  const groupType = typeof node.$type === 'string' ? node.$type : inheritedType;
  if (Object.prototype.hasOwnProperty.call(node, '$value')) {
    const type = typeof node.$type === 'string' ? node.$type : inheritedType;
    if (!type) fail(prefix.join('.') + ' has no explicit or inherited $type');
    out.push({ path: prefix.join('.'), name: '--dl-' + prefix.map(kebab).join('-'), type, value: cssValue(type, node.$value, prefix.join('.')) });
    return out;
  }
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    collect(value, [...prefix, key], groupType, out);
  }
  return out;
}
function compile() {
  const tokens = JSON.parse(fs.readFileSync(TOKEN_FILE, 'utf8'));
  if (!String(tokens.$schema || '').includes('2025.10/format.json')) fail('token file must declare the DTCG 2025.10 format schema');
  const entries = collect(tokens);
  if (entries.length < 25) fail('unexpectedly small token set: ' + entries.length);
  const names = new Set(entries.map(x => x.name));
  for (const required of ['--dl-color-surface-base','--dl-color-surface-raised','--dl-color-text-primary','--dl-color-border-default','--dl-color-accent-primary','--dl-typography-font-family-sans','--dl-typography-font-family-mono','--dl-spacing-space-4','--dl-typography-font-size-body']) {
    if (!names.has(required)) fail('required token missing: ' + required);
  }
  const lines = [
    '/* GENERATED by BEC-PRIME Elohim DesignTokenCompiler.js. DO NOT EDIT. */',
    FONT_IMPORT,
    ':root {',
    ...entries.map(x => '  ' + x.name + ': ' + x.value + ';'),
    '}',
    ''
  ];
  const css = lines.join('\n');
  const master = fs.readFileSync(MASTER_CSS, 'utf8');
  if (!master.includes('@import url("/assets/dl-design-tokens.css");')) fail('master silo stylesheet must import the generated token artifact first');
  if (!master.includes('--silo-bg:var(--dl-color-surface-base)')) fail('master silo must map its base surface to the token contract');
  if (!master.includes('html body .grid')) fail('master silo must include the enterprise-grid override');
  return css;
}
function main() {
  const expected = compile();
  if (process.argv.includes('--write')) {
    fs.writeFileSync(OUTPUT_FILE, expected, 'utf8');
    process.stdout.write('WROTE ' + path.relative(ROOT, OUTPUT_FILE) + '\n');
    return;
  }
  if (!fs.existsSync(OUTPUT_FILE)) fail('generated CSS missing; run node BEC-PRIME/compiler/DesignTokenCompiler.js --write');
  const actual = fs.readFileSync(OUTPUT_FILE, 'utf8');
  if (actual !== expected) fail('generated CSS drift; run node BEC-PRIME/compiler/DesignTokenCompiler.js --write and commit the result');
  process.stdout.write('PASS ' + entriesCount(expected) + ' generated design tokens; CSS artifact matches source contract.\n');
}
function entriesCount(css) { return (css.match(/--dl-/g) || []).length; }
try { main(); } catch (error) { process.stderr.write(String(error.message || error) + '\n'); process.exitCode = 1; }
